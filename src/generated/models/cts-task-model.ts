import type { SystemUser } from './system-user-model';
import type { CTSProject } from './cts-project-model';

export const CTSTaskPriorityKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type CTSTaskPriorityKey = keyof typeof CTSTaskPriorityKeyToLabel;

export const CTSTaskStatusKeyToLabel = {
  'NotStarted': 'Not Started',
  'InProgress': 'In Progress',
  'Submitted': 'Submitted',
  'Approved': 'Approved',
  'Completed': 'Completed'
} as const;
export type CTSTaskStatusKey = keyof typeof CTSTaskStatusKeyToLabel;

export interface CTSTask {
  /**
   * @displayName CTS Task
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Task Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  taskName: string;
  /**
   * @displayName Assigned To
   */
  assignedTo?: Pick<SystemUser, 'id' | 'fullName'>;
  /**
   * @displayName Due Date
   */
  dueDate?: string;
  /**
   * @displayName Priority
   */
  priorityKey?: CTSTaskPriorityKey;
  /**
   * @displayName Project
   */
  project?: Pick<CTSProject, 'id' | 'projectName'>;
  /**
   * @displayName Status
   */
  statusKey?: CTSTaskStatusKey;
  /**
   * @displayName Task Description
   */
  taskDescription?: string;
}

export const _CTSTask = 'CTSTask' as const;